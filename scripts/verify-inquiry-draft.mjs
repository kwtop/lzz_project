import assert from 'node:assert/strict';
import fs from 'node:fs';
import {load} from 'cheerio';
import {validateInquiry,readInquiryDraft,buildInquiryDraft} from '../src/lib/inquiryDraft.ts';
const references=[{id:'example',kind:'product',title:'Example part',legacyName:'Older title',aliases:['Prior label'],path:'/machined-parts/example/'}];
const fields={name:'Local QA',email:'audit@example.invalid',phone:'',project:'Aluminum housing, quantity 10. Please review the drawing.'};
assert.deepEqual(validateInquiry(fields),{});
const phoneOnly={...fields,email:'',phone:'+1 (202) 555-0123'};
assert.deepEqual(validateInquiry(phoneOnly),{});
assert.deepEqual(validateInquiry({...phoneOnly,email:'audit@example.invalid'}),{});
assert.ok(validateInquiry({...fields,email:'',phone:' '}).contact);
assert.ok(validateInquiry({...phoneOnly,email:'invalid'}).email);
assert.ok(validateInquiry({...phoneOnly,phone:'call me'}).phone);
assert.ok(validateInquiry({...fields,name:' '}).name);
assert.ok(validateInquiry({...fields,project:'\n '}).project);
const saved={version:2,fields:phoneOnly,referenceKey:'',prepared:true};
const restored=readInquiryDraft(JSON.stringify(saved),references,references[0]);
assert.equal(restored.prepared,true);
assert.equal(restored.reference,undefined,'explicit blank reference survives restoration');
const invalid=readInquiryDraft(JSON.stringify({...saved,fields:{...phoneOnly,phone:''}}),references);
assert.equal(invalid.prepared,false);
const legacy=readInquiryDraft(JSON.stringify({version:1,prepared:false,fields:{...fields,project:'Older title',material:'Aluminum',quantity:'10',destination:'United States'}}),references,references[0]);
assert.equal(legacy.reference.id,'example');
assert.equal(legacy.fields.project,'Material family: Aluminum\nQuantity: 10\nDestination: United States');
assert.equal(readInquiryDraft('{bad-json',references),null);
const unsafe=readInquiryDraft(JSON.stringify({...saved,referenceKey:'https://untrusted.test/'}),references);
assert.equal(unsafe.reference,undefined);
const draft=buildInquiryDraft(phoneOnly,'https://www.lzz-cnc.com',references[0]);
assert.ok(draft.body.includes('Phone / WhatsApp: +1 (202) 555-0123'));
assert.ok(!draft.body.includes('Email:'));
assert.ok(draft.body.includes('Source page: https://www.lzz-cnc.com/machined-parts/example/'));
assert.equal(new URL(draft.mail).protocol,'mailto:');
assert.equal(new URL(draft.mail).searchParams.get('body'),draft.body);
const $=load(fs.readFileSync('dist/quote/index.html','utf8'));
assert.equal($('form.inquiry-form').length,1,'form rendered into static HTML');
assert.equal($('h1').text().replace(/\s+/g,' ').trim(),'Discuss your part');
assert.equal($('input[required],textarea[required],select[required]').map((_,e)=>$(e).attr('name')).get().join(','),'name,project');
assert.equal($('input[name=email][required],input[name=phone][required],select[name=reference][required]').length,0);
assert.equal($('form').attr('action'),undefined,'draft form has no network submission endpoint');
console.log('Inquiry draft contract passed: contact alternatives, invalid inputs, optional references, legacy migration, safe context, mail draft, and static HTML.');
