export function attachmentMessage(locale:'en'|'es',message:string):string {
 if(locale==='en')return message;
 if(message.endsWith(': this file is empty. Choose a file with content.')){
  return message.replace(/: this file is empty\. Choose a file with content\.$/,': el archivo está vacío. Elige un archivo con contenido.');
 }
 if(message.endsWith(': use PDF, STEP/STP, IGES/IGS, DXF/DWG, JPG/PNG or ZIP.')){
  return message.replace(/: use PDF, STEP\/STP, IGES\/IGS, DXF\/DWG, JPG\/PNG or ZIP\.$/,': usa PDF, STEP/STP, IGES/IGS, DXF/DWG, JPG/PNG o ZIP.');
 }
 return quoteText(locale,message);
}
